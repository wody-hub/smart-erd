import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(__dirname, '..');
const sourcePath = path.join(
  repoRoot,
  'src',
  'main',
  'resources',
  'markdown',
  'markdown-sanitize-policy.json',
);
const targetPath = path.join(
  repoRoot,
  'client',
  'src',
  'collaboration',
  'plugins',
  'markdown',
  'markdown-sanitize-policy.generated.ts',
);

const source = await readFile(sourcePath, 'utf8');
const policy = JSON.parse(source);
const output = `// Generated by scripts/sync-markdown-sanitize-policy.mjs\nexport const MARKDOWN_SANITIZE_POLICY = ${JSON.stringify(policy, null, 2)} as const;\n`;

await mkdir(path.dirname(targetPath), { recursive: true });
await writeFile(targetPath, output, 'utf8');

console.log(`Synced markdown sanitize policy to ${path.relative(repoRoot, targetPath)}`);
